use std::{
    fs::File,
    io::{self, BufWriter, Read, Write},
    path::Path,
};

use serde::Serialize;

use super::query::Record;

pub const HEX_FILE: &str = ".sonark-import.hex";
pub const OUTPUT: &str = "log-derived.pcapng";
const MAX_INPUT: u64 = 64 * 1024 * 1024;
const MAX_PDU: usize = 128 * 1024;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Format {
    Http,
    Json,
    Text,
}

impl Format {
    pub fn dissector(self) -> &'static str {
        match self {
            Self::Http => "http",
            Self::Json => "json",
            Self::Text => "data",
        }
    }

    pub fn interface(self) -> &'static str {
        match self {
            Self::Http => "SonarK synthetic HTTP log PDUs",
            Self::Json => "SonarK synthetic JSON log PDUs",
            Self::Text => "SonarK synthetic text log PDUs",
        }
    }

    pub fn writes_recorded_time(self) -> bool {
        self == Self::Http
    }
}

#[derive(Serialize)]
struct Manifest<'a> {
    synthetic: bool,
    source: &'a Path,
    representation: Format,
    records: usize,
    pdus: usize,
    timestamps: &'static str,
}

pub fn prepare(source: &Path, directory: &Path, force_text: bool) -> io::Result<Format> {
    let mut bytes = Vec::new();
    File::open(source)?.take(MAX_INPUT + 1).read_to_end(&mut bytes)?;
    if bytes.len() as u64 > MAX_INPUT {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "Log exceeds the 64 MiB conversion limit"));
    }
    if bytes.is_empty() || bytes.contains(&0) {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "Expected a nonempty text log"));
    }

    let encoding = if force_text { Format::Text } else { detect(&bytes) };
    let mut writer = BufWriter::new(File::create(directory.join(HEX_FILE))?);
    let mut records = 0;
    let mut pdus = 0;
    match encoding {
        Format::Http => {
            for line in std::str::from_utf8(&bytes).expect("detected text").lines().filter(|line| !line.trim().is_empty()) {
                let record = Record::parse(line).expect("detected HTTP record");
                let timestamp = iso_timestamp(record.timestamp).expect("detected valid timestamp");
                records += 1;
                if let Some(request) = http_request(&record, records) {
                    write_octets(&mut writer, Some(&timestamp), request.as_bytes())?;
                    pdus += 1;
                }
                let response = http_response(&record, records);
                write_octets(&mut writer, Some(&timestamp), response.as_bytes())?;
                pdus += 1;
            }
        }
        Format::Json => {
            let split = bytes.split_inclusive(|&b| b == b'\n').filter(|line| !line.iter().all(u8::is_ascii_whitespace));
            if json_lines(&bytes) {
                for line in split {
                    write_octets(&mut writer, None, line)?;
                    records += 1;
                    pdus += 1;
                }
            } else {
                write_octets(&mut writer, None, &bytes)?;
                records = 1;
                pdus = 1;
            }
        }
        Format::Text => {
            for line in bytes.split_inclusive(|&b| b == b'\n') {
                records += 1;
                for chunk in line.chunks(MAX_PDU) {
                    write_octets(&mut writer, None, chunk)?;
                    pdus += 1;
                }
            }
        }
    }
    writer.flush()?;
    crate::project::write_json(&directory.join("source.json"), &Manifest {
        synthetic: true,
        source,
        representation: encoding,
        records,
        pdus,
        timestamps: if encoding.writes_recorded_time() {
            "HTTP log event timestamps; request and response share the recorded time"
        } else {
            "Generated by text2pcap; not sourced from log events"
        },
    })?;
    Ok(encoding)
}

fn detect(bytes: &[u8]) -> Format {
    if let Ok(text) = std::str::from_utf8(bytes) {
        let mut lines = text.lines().filter(|line| !line.trim().is_empty()).peekable();
        if lines.peek().is_some() && lines.all(|line| {
            line.len() <= MAX_PDU / 4
                && Record::parse(line).is_some_and(|record| iso_timestamp(record.timestamp).is_some())
        }) {
            return Format::Http;
        }
    }
    if json_lines(bytes) || json_document(bytes) {
        Format::Json
    } else {
        Format::Text
    }
}

fn json_lines(bytes: &[u8]) -> bool {
    let mut lines = bytes.split_inclusive(|&b| b == b'\n')
        .filter(|line| !line.iter().all(u8::is_ascii_whitespace)).peekable();
    lines.peek().is_some() && lines.all(json_document)
}

fn json_document(bytes: &[u8]) -> bool {
    bytes.len() <= MAX_PDU && matches!(
        serde_json::from_slice(bytes),
        Ok(serde_json::Value::Array(_) | serde_json::Value::Object(_))
    )
}

fn write_octets(writer: &mut impl Write, timestamp: Option<&str>, payload: &[u8]) -> io::Result<()> {
    if let Some(timestamp) = timestamp {
        writeln!(writer, "{timestamp}")?;
    }
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut line = Vec::with_capacity(56);
    for (index, chunk) in payload.chunks(16).enumerate() {
        line.clear();
        write!(line, "{:06x}", index * 16)?;
        for &byte in chunk {
            line.push(b' ');
            line.push(HEX[(byte >> 4) as usize]);
            line.push(HEX[(byte & 0xf) as usize]);
        }
        line.push(b'\n');
        writer.write_all(&line)?;
    }
    writer.write_all(b"\n")
}

fn http_request(record: &Record<'_>, number: usize) -> Option<String> {
    let (method, target, protocol) = record.request_triplet();
    let (method, target) = (method?, target?);
    if !method.bytes().all(|b| b.is_ascii_uppercase() || b == b'-')
        || !target.bytes().all(|b| b.is_ascii_graphic())
    {
        return None;
    }
    let version = match protocol {
        Some("HTTP/1.0") => "HTTP/1.0",
        _ => "HTTP/1.1",
    };
    let mut message = format!("{method} {target} {version}\r\n");
    header(&mut message, "Referer", record.referer);
    header(&mut message, "User-Agent", record.user_agent);
    header(&mut message, "X-SonarK-Logged-Protocol", protocol);
    shared_headers(&mut message, record, number);
    message.push_str("\r\n");
    Some(message)
}

fn http_response(record: &Record<'_>, number: usize) -> String {
    let mut message = format!("HTTP/1.1 {} Log-derived\r\n", record.status);
    shared_headers(&mut message, record, number);
    message.push_str(&format!("X-SonarK-Logged-Bytes: {}\r\nContent-Length: 0\r\n\r\n", record.bytes));
    message
}

fn shared_headers(message: &mut String, record: &Record<'_>, number: usize) {
    message.push_str(&format!("X-SonarK-Record: {number}\r\n"));
    header(message, "X-SonarK-Logged-Client", Some(record.client));
}

fn header(message: &mut String, name: &str, value: Option<&str>) {
    if let Some(value) = value.filter(|value| *value != "-" && !value.chars().any(char::is_control)) {
        message.push_str(&format!("{name}: {value}\r\n"));
    }
}

fn iso_timestamp(timestamp: &str) -> Option<String> {
    let (date_time, zone) = timestamp.split_once(' ')?;
    let mut date = date_time.splitn(3, '/');
    let day: u32 = date.next()?.parse().ok()?;
    iso_parts(day, date.next()?, date.next()?, zone)
}

fn iso_parts(day: u32, month: &str, year_time: &str, zone: &str) -> Option<String> {
    let months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    let month = months.iter().position(|value| *value == month)? + 1;
    let (year, time) = year_time.split_once(':')?;
    let year: u32 = year.parse().ok()?;
    let leap = year.is_multiple_of(4) && (!year.is_multiple_of(100) || year.is_multiple_of(400));
    let month_days = [31, 28 + u32::from(leap), 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
    let mut clock = time.split(':');
    let hour = clock.next()?.parse::<u32>().ok()?;
    let minute = clock.next()?.parse::<u32>().ok()?;
    let second = clock.next()?.parse::<u32>().ok()?;
    if !(1..=month_days[month - 1]).contains(&day)
        || !(1970..=9999).contains(&year) || hour > 23 || minute > 59 || second > 59
        || clock.next().is_some() || zone.len() != 5
        || !matches!(zone.as_bytes()[0], b'+' | b'-')
        || !zone.as_bytes()[1..].iter().all(u8::is_ascii_digit)
    {
        return None;
    }
    let offset_hour = zone[1..3].parse::<u32>().ok()?;
    let offset_minute = zone[3..].parse::<u32>().ok()?;
    if offset_hour > 23 || offset_minute > 59 {
        return None;
    }
    Some(format!("{year:04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}{}:{offset_minute:02}", &zone[..3]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_http_json_and_mixed_text_without_dropping_records() {
        let log = br#"192.0.2.1 - - [29/Feb/2024:12:00:00 -0300] "GET / HTTP/1.1" 200 12"#;
        assert_eq!(detect(log), Format::Http);
        assert_eq!(detect(b"{\"code\":200}\n{\"code\":404}\n"), Format::Json);
        let mixed = [log.as_slice(), b"\nextra line\n"].concat();
        assert_eq!(detect(&mixed), Format::Text);
        assert_eq!(iso_timestamp("29/Feb/2024:12:00:00 -0300").as_deref(), Some("2024-02-29T12:00:00-03:00"));
        assert!(iso_timestamp("29/Feb/2023:12:00:00 -0300").is_none());
    }
}
